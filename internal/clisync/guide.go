package clisync

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/yangk/kshell/internal/skills"
)

// guideTemplate 生成自助安装说明书 ~/.kshell/host-install.md：写给「其它平台
// 的 AI」看的安装指引——用户把一句话指令复制给 Claude Code / Cursor 等宿主
// 的 agent，agent 读这份文件自助完成安装。SKILL.md 全文内嵌（AI 只做拷贝，
// 不生成内容，提示注入面最小）；版本行参与哈希，升级后自愈重写。
//
// 模板里的 § 是反引号占位（raw string 里写不了反引号），组装后统一替换。
const guideTemplate = `# kshell host installation guide (for AI agents)

You (an AI agent running inside another host tool) are asked to install the
kshell skill into your own skills directory. Follow the steps below exactly.

## Safety boundary

- ONLY write to §<your skills root>/kshell/§ (see the table below for your
  skills root).
- Do NOT modify PATH, other skills, or any other configuration. (Adding
  ~/.kshell/bin to PATH is an optional step you may skip.)
- Do NOT execute anything beyond copying the SKILL.md content below and the
  optional verification command.

## Your skills root

§%s§

## Steps

1. Create §<your skills root>/kshell/§ if it does not exist.
2. Write the SKILL.md content below to §<your skills root>/kshell/SKILL.md§
   (UTF-8, verbatim, no edits).
3. Verify: run the CLI with an absolute path (works even if PATH is not set):
   §%s§. It prints the kshell agent usage. The kshell desktop app must be
   running for the commands to work (exit code 3 otherwise); §kshell agent
   list --json§ should return the session list.
4. Optional: add the bin directory to your user PATH so plain §kshell§ works
   in new terminals: §%s§.

## SKILL.md content (copy verbatim)

§%s§

---

> Generated by kshell %s. Re-run the sync in kshell settings after upgrading,
> then ask the host agent to reinstall to pick up the new version.
`

// buildGuideMD 组装说明书。SKILL.md 全文复用 buildSkillMD（同一事实源），
// 目录对照表由 skills.targetRel 解析出本机真实路径。
func buildGuideMD(home, ver string) string {
	if ver == "" {
		ver = "unknown"
	}
	var table strings.Builder
	for _, id := range KnownHostIDs() {
		if root, ok := skills.TargetRoot(id, home); ok {
			fmt.Fprintf(&table, "- %s: %s\n", id, root)
		}
	}
	exe := filepath.Join(BinDir(home), BinaryName())
	out := fmt.Sprintf(guideTemplate,
		table.String(),
		exe,
		filepath.Dir(exe),
		buildSkillMD(ver),
		ver,
	)
	return strings.ReplaceAll(out, "§", "`")
}

// installGuide 把说明书写入 ~/.kshell/host-install.md。内容哈希门控，相同跳过。
// 返回 (状态, wire key 错误)；错误形态 err.hostsync.guide_write|<原因>。
func installGuide(home, ver string) (string, string) {
	target := filepath.Join(home, ".kshell", "host-install.md")
	if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
		return stateError, "err.hostsync.guide_write|" + err.Error()
	}
	content := buildGuideMD(home, ver)
	if cur, err := os.ReadFile(target); err == nil && string(cur) == string(content) {
		return stateCurrent, ""
	}
	// 临时文件 + rename：与技能写入同口径，避免读到半截文件。
	tmp := target + ".tmp"
	if err := os.WriteFile(tmp, []byte(content), 0o644); err != nil {
		return stateError, "err.hostsync.guide_write|" + err.Error()
	}
	if err := os.Rename(tmp, target); err != nil {
		_ = os.Remove(tmp)
		return stateError, "err.hostsync.guide_write|" + err.Error()
	}
	return skillInstalled, ""
}
